// Generates art/src/tiles/wall-0..15.svg: 16-tile auto-tiling (SPEC.md §5.4).
// mask bits = neighbours that are also walls: N=1, E=2, S=4, W=8.
// Outlines and rounded corners only on open edges, so wall masses merge into one shape.
// A front face shows when the cell below is open (top-down 3/4 view).
import { writeFileSync } from 'node:fs';

const T = 64, FACE = 20, R = 6;
const ink = 'stroke="var(--ink)" stroke-width="1.8" stroke-linejoin="round" stroke-linecap="round" fill="none"';

function tile(mask: number): string {
  const n = !(mask & 1), e = !(mask & 2), s = !(mask & 4), w = !(mask & 8); // true = open edge
  const top = s ? T - FACE : T;
  // Corner radii: round only where both edges meeting there are open.
  const rNW = n && w ? R : 0, rNE = n && e ? R : 0, rSE = s && e ? R : 0, rSW = s && w ? R : 0;
  const outline = (y0: number, y1: number, rTL: number, rTR: number, rBR: number, rBL: number) =>
    `M ${rTL} ${y0} L ${T - rTR} ${y0} A ${rTR} ${rTR} 0 0 1 ${T} ${y0 + rTR} L ${T} ${y1 - rBR} A ${rBR} ${rBR} 0 0 1 ${T - rBR} ${y1} ` +
    `L ${rBL} ${y1} A ${rBL} ${rBL} 0 0 1 0 ${y1 - rBL} L 0 ${y0 + rTL} A ${rTL} ${rTL} 0 0 1 ${rTL} ${y0} Z`;

  // Deterministic stone-block seams on the top face, varied by mask.
  const sx = 18 + ((mask * 7) % 22), sy = Math.round(top * (0.35 + ((mask * 5) % 4) * 0.08));
  const sx2 = sx + 14 + ((mask * 3) % 10);
  const seams = [
    `M ${sx} 0 Q ${sx + 2} ${sy / 2} ${sx - 1} ${sy}`,
    `M 0 ${sy} Q ${T / 2} ${sy + 2} ${T} ${sy - 1}`,
    `M ${sx2} ${sy} Q ${sx2 + 2} ${(sy + top) / 2} ${sx2 - 1} ${top}`,
  ];

  // Ink only on open edges.
  const edges: string[] = [];
  if (n) edges.push(`M ${rNW} 0 L ${T - rNE} 0`);
  if (e) edges.push(`M ${T} ${rNE} L ${T} ${T - rSE}`);
  if (s) edges.push(`M ${T - rSE} ${T} L ${rSW} ${T}`);
  if (w) edges.push(`M 0 ${T - rSW} L 0 ${rNW}`);
  if (rNW) edges.push(`M 0 ${R} A ${R} ${R} 0 0 1 ${R} 0`);
  if (rNE) edges.push(`M ${T - R} 0 A ${R} ${R} 0 0 1 ${T} ${R}`);
  if (rSE) edges.push(`M ${T} ${T - R} A ${R} ${R} 0 0 1 ${T - R} ${T}`);
  if (rSW) edges.push(`M ${R} ${T} A ${R} ${R} 0 0 1 0 ${T - R}`);

  // Light from the top-left: highlight the open north and west edges of the top face.
  const hl: string[] = [];
  if (n) hl.push(`M ${rNW + 2} 2.2 L ${T - rNE - 2} 2.2`);
  if (w) hl.push(`M 2.2 ${rNW + 2} L 2.2 ${top - 2}`);

  const face = s ? `
  <path d="${outline(top, T, 0, 0, rSE, rSW)}" fill="var(--wall-face)"/>
  <path d="${outline(top, T, 0, 0, rSE, rSW)}" fill="url(#hatch)"/>
  <path d="M ${rSW} ${T - 3.5} L ${T - rSE} ${T - 3.5} L ${T - rSE} ${T} L ${rSW} ${T} Z" fill="var(--wall-shade)"/>
  <g filter="url(#wobble-soft)" stroke="var(--wall-shade)" stroke-width="1.3" fill="none">
    <path d="M ${12 + (mask % 3) * 4} ${top + 1} L ${13 + (mask % 3) * 4} ${T - 4}"/>
    <path d="M ${36 + (mask % 4) * 3} ${top + 1} L ${35 + (mask % 4) * 3} ${T - 4}"/>
  </g>
  <g filter="url(#wobble-soft)" ${ink}><path d="M 0 ${top} L ${T} ${top}"/></g>` : '';

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${T}" height="${T}" viewBox="0 0 ${T} ${T}" data-palettes="heads,tails,heads2,tails2,heads3,tails3,heads4,tails4,heads5,tails5,heads6,tails6">
  <!-- generated by tools/gen-walls.ts, mask ${mask} (N=1 E=2 S=4 W=8) -->
  <path d="${outline(0, top, rNW, rNE, s ? 0 : rSE, s ? 0 : rSW)}" fill="var(--wall-top)"/>
  <g filter="url(#wobble-soft)" stroke="var(--wall-shade)" stroke-width="1.2" stroke-opacity="0.7" stroke-linecap="round" fill="none">
    ${seams.map((d) => `<path d="${d}"/>`).join('\n    ')}
  </g>
  ${hl.length ? `<path d="${hl.join(' ')}" stroke="var(--highlight)" stroke-width="1.6" stroke-opacity="0.55" stroke-linecap="round" fill="none"/>` : ''}${face}
  ${edges.length ? `<g filter="url(#wobble)" ${ink}><path d="${edges.join(' ')}"/></g>` : ''}
</svg>
`;
}

for (let m = 0; m < 16; m++) writeFileSync(`art/src/tiles/wall-${m}.svg`, tile(m));
console.log('wrote art/src/tiles/wall-0..15.svg');
